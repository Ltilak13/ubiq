"""Decision records: the cross-record checks and the generated index.

A decision record (`docs/decisions/NNNN-name.md`, bound to `.ubiq/schemas/decision.json`)
is validated one file at a time by its schema. This module checks what a schema
cannot see across files, and generates the list of decisions that the map shows as
"Decisions so far":

- A `superseded` decision is named by exactly one other decision's `supersedes`, and a
  decision that supersedes another one is not itself `proposed`.
- The index block between `INDEX_START` and `INDEX_END` in the decisions README equals
  what the records generate. `ubiq decisions --write` rewrites it; `ubiq check` reports
  a stale block as E009 at the marker.

The block is plain Markdown in a repository file. Mirroring it into the body of a
tracking issue is a later step and needs one more fact in `ubiq.sync.FACTS`.
"""
from __future__ import annotations

import re
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

import yaml

from .check import Diagnostic
from .globs import GlobError
from .schemas import load_data

INDEX_START = "<!-- ubiq-decisions:start -->"
INDEX_END = "<!-- ubiq-decisions:end -->"
BLOCK_RE = re.compile(re.escape(INDEX_START) + r".*?" + re.escape(INDEX_END), re.DOTALL)
LOAD_ERRORS = (OSError, UnicodeError, ValueError, TypeError, KeyError, yaml.YAMLError, RecursionError)


def decision_paths(cfg) -> list[Path]:
    """The files that `sync.records` selects as `decision` records."""
    if cfg.sync is None:
        return []
    paths: set[Path] = set()
    for record in cfg.sync.records:
        if record.kind == "decision":
            try:
                paths.update(record.glob.walk(cfg.ignore))
            except GlobError:
                continue
    return sorted(paths)


def load_decisions(cfg) -> list[dict[str, Any]]:
    """Readable decision records in file order. Unreadable or malformed ones are skipped (E005/E009 report them)."""
    found = []
    for path in decision_paths(cfg):
        try:
            data = load_data(path, frontmatter=True)
            found.append({"name": data["name"], "question": data["question"], "status": data["status"],
                          "decided": str(data["decided"]), "by": data["by"],
                          "options": list(data["options"]), "outcome": list(data["outcome"]),
                          "supersedes": data.get("supersedes", ""),
                          "path": path.relative_to(cfg.root).as_posix(), "file": path})
        except LOAD_ERRORS:
            continue
    return found


def replacements(decisions: Sequence[Mapping[str, Any]]) -> dict[str, str]:
    """Decision name -> the name of the decision that supersedes it."""
    return {d["supersedes"]: d["name"] for d in decisions if d["supersedes"]}


def index_block(decisions: Sequence[Mapping[str, Any]]) -> str:
    """The generated Markdown list, markers included. Newest decision last, as numbered."""
    replaced = replacements(decisions)
    lines = [INDEX_START, "<!-- Generated by `ubiq decisions --write`; edit the records, not this list. -->", "",
             "| Decision | Question | Status | Decided |", "| --- | --- | --- | --- |"]
    for d in decisions:
        status = d["status"] + (f" by [[decision:{replaced[d['name']]}]]" if d["name"] in replaced else "")
        lines.append(f"| [[decision:{d['name']}]] | #{d['question']} | {status} | {d['decided']} |")
    return "\n".join([*lines, INDEX_END])


def index_path(cfg) -> Path:
    """The README beside the decision records, which holds the generated block."""
    paths = decision_paths(cfg)
    return (paths[0].parent if paths else cfg.root / "docs/decisions") / "README.md"


def render_index(text: str, decisions: Sequence[Mapping[str, Any]]) -> str | None:
    """`text` with its block replaced, or None when it has no block."""
    if len(BLOCK_RE.findall(text)) != 1:
        return None
    return BLOCK_RE.sub(lambda _m: index_block(decisions), text)


def decision_diagnostics(cfg) -> list[Diagnostic]:
    """E009 for a broken supersession and for a missing or stale index block."""
    decisions = load_decisions(cfg)
    if not decisions:
        return []
    found: list[Diagnostic] = []
    by_name = {d["name"]: d for d in decisions}
    replaced = replacements(decisions)
    claimed: dict[str, list[str]] = {}
    for d in decisions:
        if d["supersedes"]:
            claimed.setdefault(d["supersedes"], []).append(d["name"])
    for name, claimers in sorted(claimed.items()):
        if len(claimers) > 1:
            found.append(Diagnostic("E009", f"decision '{name}' is superseded by more than one decision: "
                                            f"{', '.join(sorted(claimers))}", by_name[claimers[0]]["file"]))
    for d in decisions:
        if d["supersedes"] == d["name"]:
            found.append(Diagnostic("E009", "a decision cannot supersede itself", d["file"]))
        elif d["supersedes"] in by_name and by_name[d["supersedes"]]["status"] != "superseded":
            found.append(Diagnostic(
                "E009", f"supersedes '{d['supersedes']}', whose status is "
                        f"'{by_name[d['supersedes']]['status']}', not 'superseded'", d["file"]))
        if d["status"] == "superseded" and d["name"] not in replaced:
            found.append(Diagnostic("E009", "status is superseded but no decision supersedes it", d["file"]))
    readme = index_path(cfg)
    try:
        text = readme.read_text(encoding="utf-8")
    except OSError:
        return found
    want = render_index(text, decisions)
    if want is None:
        found.append(Diagnostic("E009", f"{readme.name} needs one generated decision list between "
                                        f"{INDEX_START} and {INDEX_END}", readme))
    elif want != text:
        found.append(Diagnostic("E009", "the generated decision list is out of date; "
                                        "run `ubiq decisions --write`", readme,
                                text.count("\n", 0, text.index(INDEX_START)) + 1))
    return found


def cmd_decisions(args) -> int:
    """`ubiq decisions`: print the generated list, or `--write` it into the README."""
    from .config import load_config
    cfg = load_config(Path(args.root).resolve())
    decisions = load_decisions(cfg)
    if not args.write:
        print(index_block(decisions))
        return 0
    readme = index_path(cfg)
    try:
        text = readme.read_text(encoding="utf-8")
    except OSError as exc:
        print(f"error: cannot read {readme}: {exc}")
        return 2
    new = render_index(text, decisions)
    if new is None:
        print(f"error: {readme} needs one {INDEX_START} ... {INDEX_END} block")
        return 2
    if new != text:
        readme.write_text(new, encoding="utf-8")
    return 0
